// تمرین ۲: برنامه‌ای بنویسید که با استفاده از if بررسی کند آیا نمره دانشجو حداقل ۱۰ است یا خیر.

void main() {
  double score = 12.5; // می‌توانید این مقدار را تغییر دهید

  if (score >= 10) {
    print('نمره دانشجو قابل قبول است (حداقل ۱۰).');
  } else {
    print('نمره دانشجو کمتر از ۱۰ است و قابل قبول نیست.');
  }
}
