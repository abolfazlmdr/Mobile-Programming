// تمرین ۶: یک Map ایجاد کنید که نام سه دانشجو و نمره هرکدام را نگهداری کند.

void main() {
  Map<String, double> scores = {
    'علی رضایی': 18.5,
    'سارا احمدی': 19.0,
    'رضا کریمی': 16.5,
  };

  print('نمرات دانشجویان:');
  scores.forEach((name, score) {
    print('$name: $score');
  });

  // دسترسی به یک نمره خاص
  print('\nنمره سارا احمدی: ${scores['سارا احمدی']}');
}
